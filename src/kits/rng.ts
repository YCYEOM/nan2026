// 시드 난수 키트. 게임 5종이 각자 LCG 를 복사해 들고 있던 것을 여기 하나로 모았다.
//
// 복사본에 결함이 두 개 있었고 둘 다 복사본 수만큼 존재했다:
//  1) LCG 는 **이웃 시드끼리 첫 출력이 거의 같다.** 시드 1~40 이 전부 같은 값을 주는 것을
//     제로섬 배치 추첨 테스트가 잡았다. 워밍업으로 완화할 수는 있지만 상수를 눈으로 골라야 하고
//     8회면 0,2,0,2 주기가 남았다 — 완화지 해결이 아니다.
//  2) `0xffffffff` 로 나누면 **정확히 1.0 이 나올 수 있다.** 그러면 `Math.floor(rnd()*n)` 이
//     `n` 을 돌려줘 배열 범위를 벗어난다(리듬은 비트 시각이 NaN 이 됐다).
//
// splitmix32 는 시드를 통과시키기 전에 섞으므로 이웃 시드가 즉시 갈라지고,
// 2^32 로 나누므로 [0, 1) 이 보장된다 — 워밍업도 상수 튜닝도 필요 없다.

/** 시드 난수 생성기. 같은 시드는 같은 수열, 반환값은 항상 `[0, 1)`. */
export function rng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x9e3779b9) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
